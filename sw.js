// ============================================================================
// SERVICE WORKER — офлайн-оболочка приложения. Версия 3.1 (рефакторинг)
// ============================================================================
// РОЛЬ ЭТОГО ФАЙЛА: работает в фоне, без интерфейса, и делает две вещи:
//   1. При первой установке скачивает файлы приложения (HTML, JS, иконки)
//      в постоянную память телефона — благодаря этому форма открывается
//      даже без интернета (режим «полет», подвалы, трасса).
//   2. Перехватывает запросы файлов: при наличии сети обновляет кэш свежими
//      версиями (водители автоматически получают обновления), при отсутствии
//      сети отдает файлы из памяти телефона.
//
// СТРАТЕГИЯ NETWORK-FIRST («сначала сеть, потом кэш»):
//   онлайн  -> файл берется из интернета (свежий) и попутно обновляется в кэше;
//   офлайн  -> файл берется из кэша телефона.
//   ЗАЧЕМ так: обновление у водителей происходит само, без их участия —
//   достаточно залить новые файлы на хостинг и поднять версию ниже.
// ============================================================================

// Версия кэша. ПРАВИЛО: изменили любой файл сайта -> увеличили номер (v9 -> v10).
// Браузер увидит новое имя, сотрет старый кэш целиком и скачает свежие файлы.
const CACHE_NAME = 'driver-pwa-v10';

// Оболочка приложения: минимальный набор для работы офлайн.
// Иконки в списке, чтобы ярлык/логотип показывались даже без сети.
const ASSETS_TO_CACHE = [
    './',                     // корень сайта (страница приложения)
    './index.html',           // разметка и стили формы
    './app.js',               // логика очереди и отправки
    './manifest.json',        // конфигурация PWA-ярлыка
    './icon-192.png',
    './icon-512.png',
    './apple-touch-icon.png'
];

// ============================================================================
// ЭТАП 1: УСТАНОВКА (первое открытие приложения или выход новой версии)
// ============================================================================
self.addEventListener('install', (event) => {
    event.waitUntil(
        caches.open(CACHE_NAME).then((cache) => {
            // ИСПРАВЛЕНО (важно): раньше был cache.addAll() — режим «всё или ничего».
            // Если на хостинге отсутствует ХОТЬ ОДИН файл из списка (например,
            // забыли залить иконку), установка воркера падала ЦЕЛИКОМ и приложение
            // не работало офлайн вообще. Теперь каждый файл качается независимо:
            // отсутствие второстепенного файла не ломает каркас приложения.
            return Promise.all(
                ASSETS_TO_CACHE.map((path) =>
                    cache.add(path).catch((err) => {
                        console.warn('SW: не удалось закэшировать', path, err);
                    })
                )
            );
        }).then(() => self.skipWaiting())
        // skipWaiting: новый воркер активируется немедленно, не дожидаясь,
        // пока водитель закроет все вкладки приложения
    );
});

// ============================================================================
// ЭТАП 2: АКТИВАЦИЯ — чистка старых версий кэша
// ============================================================================
self.addEventListener('activate', (event) => {
    event.waitUntil(
        caches.keys()
            .then((keys) => Promise.all(
                // Удаляем ВСЕ кэши с другими номерами версии (v7, v8, v9...),
                // чтобы старые файлы не занимали память телефона и не путали
                // приложение смесью старого и нового кода
                keys.filter((key) => key !== CACHE_NAME)
                    .map((key) => caches.delete(key))
            ))
            .then(() => self.clients.claim())
            // claim: новый воркер сразу берет под контроль уже открытые вкладки —
            // обновление применяется без перезагрузки телефона
    );
});

// ============================================================================
// ЭТАП 3: ПЕРЕХВАТ ЗАПРОСОВ
// ============================================================================
self.addEventListener('fetch', (event) => {
    const req = event.request;

    // Правило 1: POST-запросы (отправка отчетов в Google) не перехватываем.
    // Ими управляет очередь в app.js — вмешательство воркера сломало бы её.
    if (req.method !== 'GET') return;

    // Правило 2 (исправлено): обрабатываем ТОЛЬКО файлы нашего сайта.
    // Раньше перехватывались все запросы подряд, включая сторонние, — теперь
    // чужие домены проходят мимо воркера без изменений.
    const url = new URL(req.url);
    if (url.origin !== self.location.origin) return;

    event.respondWith(
        // Пытаемся получить свежий файл из сети...
        fetch(req)
            .then((networkResponse) => {
                // В кэш кладем только успешные ответы нашего же сайта.
                // status 200 + type 'basic' отсекают страницы ошибок и
                // непрозрачные (opaque) ответы сторонних ресурсов — их
                // кэшировать нельзя ни в коем случае.
                const okToCache = networkResponse &&
                                  networkResponse.status === 200 &&
                                  networkResponse.type === 'basic';

                if (okToCache) {
                    // Поток ответа можно прочитать только ОДИН раз: оригинал
                    // отдаем на экран, клон — в кэш на будущее
                    const clone = networkResponse.clone();
                    caches.open(CACHE_NAME)
                        .then((cache) => cache.put(req, clone))
                        .catch(() => {}); // сбой кэширования не должен ломать ответ
                }
                return networkResponse;
            })
            .catch(() =>
                // ...сети нет — ищем файл в памяти телефона
                caches.match(req).then((cached) => {
                    if (cached) return cached;
                    // Переход по ссылке в офлайне: отдаем сохраненный каркас
                    // приложения, чтобы вместо формы не был белый экран
                    if (req.mode === 'navigate') {
                        return caches.match('./index.html');
                    }
                    // Файла нет ни в кэше, ни в сети — честная сетевая ошибка
                    return Response.error();
                })
            )
    );
});
