/**
 * ЧТО делает: декодирует каждый Base64-элемент в JPEG и кладет в папку
 * FOLDER_ID. Сбой ОДНОГО фото не мешает остальным и не отменяет отчет:
 * в ячейке «Фото» будет и ссылка на успешные, и пояснение по сбойным.
 *
 * @param {Array|null} photoList - массив чистых Base64-строк (без data:-заголовка)
 * @param {string} safeName      - имя водителя (уже очищенное)
 * @return {Array<{text: string, url: string}>} части для ячейки «Фото»:
 *         с url = кликабельная ссылка, без url = текст пояснения об ошибке
 */
function uploadPhotos(photoList, safeName) {
  if (!photoList || !photoList.length) return [];

  var parts = [];
  // Одна метка времени на ВСЕ фото отчета + номер фото: имена не пересекутся
  // даже при загрузке нескольких файлов в одну секунду.
  var dateStr = Utilities.formatDate(new Date(), SERVER_TZ, 'yyyy-MM-dd_HH-mm-ss');

  for (var i = 0; i < photoList.length; i++) {
    var n = i + 1;
    try {
      var fileName = safeName + '_' + dateStr + '_' + n + '.jpg';
      var blob = Utilities.newBlob(
        Utilities.base64Decode(photoList[i]), 'image/jpeg', fileName);

      var f = Drive.Files.create({
        name: fileName,
        mimeType: 'image/jpeg',
        parents: [FOLDER_ID]
      }, blob, { fields: 'id, webViewLink' });

      // «Просмотр по ссылке для всех». Права могли унаследоваться от папки —
      // повторная установка не нужна и НЕ считается ошибкой.
      try {
        Drive.Permissions.create({ role: 'reader', type: 'anyone' }, f.id);
      } catch (pErr) {
        Logger.log('Предупреждение прав доступа (не критично): ' + pErr.message);
      }

      parts.push({ text: '📷 Фото ' + n, url: f.webViewLink });

    } catch (driveErr) {
      // Сбой одного фото: отчет спасаем, в ячейке будет пояснение
      Logger.log('ОШИБКА ЗАГРУЗКИ ФОТО #' + n + ': ' + driveErr.message);
      parts.push({ text: 'Фото ' + n + ': ошибка (' + driveErr.message + ')' });
    }
  }
  return parts;
}

// ============================================================================
// ГЛАВНЫЙ ПРИЕМНИК ОТЧЕТОВ (POST-запросы от телефона водителя)
// ============================================================================
function doPost(e) {
  try {
    // --- Валидация запроса до всего остального. КОДЫ здесь = VALIDATION:
    // мусорный запрос не будет корректным НИКОГДА, телефон его отложит ---
    if (!e || !e.postData || !e.postData.contents) {
      return jsonError('VALIDATION', 'Получен пустой запрос.');
    }

    var data;
    try {
      data = JSON.parse(e.postData.contents);
    } catch (parseErr) {
      return jsonError('VALIDATION', 'Тело запроса не является корректным JSON.');
    }

    if (data.action !== 'REPORT') {
      return jsonError('VALIDATION', 'Недопустимое действие: ' + data.action);
    }
    if (!data.user || !data.pointName) {
      return jsonError('VALIDATION', 'Отсутствуют обязательные поля: водитель или торговая точка.');
    }

    // Санитизация ФИО для имени листа: запрещенные символы -> '_', до 50 симв.
    var safeName = String(data.user)
      .replace(/[\\/*?:\[\]']/g, '_')
      .trim()
      .substring(0, 50) || 'Без имени';

    // ------------------------------------------------------------------
    // НОВОЕ (v3.4): БЫСТРАЯ ПРОВЕРКА ДУБЛЯ ДО ЗАГРУЗКИ ФОТО.
    // Раньше повторная отправка (ретрай после обрыва связи) СНАЧАЛА грузила
    // все фото на Диск и лишь под замком натыкалась на проверку дублей —
    // в папке Drive накапливались мусорные копии файлов. Теперь известный
    // дубль отсеивается мгновенно, без единой операции Drive.
    // Авторитетная проверка под замком (ШАГ 3 ниже) остается на месте,
    // поэтому гонок и пропусков дублей нет.
    // ------------------------------------------------------------------
    try {
      if (dedupHas(safeName, data.reportId)) {
        Logger.log('Дубль отклонен на раннем этапе (без загрузки фото): ' + data.reportId);
        return jsonOut({ status: 'success', duplicate: true, sheetName: safeName });
      }
    } catch (earlyErr) {
      // Память дублей недоступна прямо сейчас — не мешаем обычному потоку:
      // авторитетная проверка под замком все равно выполнится.
      Logger.log('Ранняя проверка дубля пропущена: ' + earlyErr.message);
    }

    // ------------------------------------------------------------------
    // ПРЕДПРОБНАЯ ПРОВЕРКА ЗАГРУЗКИ СЕРВЕРА (fail-fast оптимизация).
    // Это НЕ гарантия: между probe и записью лок может занять другой
    // водитель — тогда честно постоим в tryLock(30000) ниже. Цена этой
    // гонки — секунды ожидания, а НЕ данные. Смысл: не тратить 3-5 секунд
    // на загрузку фото, если сервер явно занят.
    // ------------------------------------------------------------------
    var probeLock = LockService.getScriptLock();
    if (!probeLock.tryLock(1000)) {
      return jsonError('BUSY', 'Сервер перегружен другими водителями. Отчет остался в телефоне и отправится повторно автоматически.');
    }
    try { probeLock.releaseLock(); } catch (relErr) {}

    // ------------------------------------------------------------------
    // ШАГ 1: фото на Диск — БЕЗ блокировки.
    // ЗАЧЕМ: фото-загрузка занимает секунды и не касается Таблицы вообще.
    // Замок берется только на запись строки (~0.3 сек), поэтому
    // одновременная отправка от 5-10 водителей проходит без «Сервер занят».
    // ------------------------------------------------------------------
    var photoParts = uploadPhotos(data.photos, safeName);

    // ------------------------------------------------------------------
    // ШАГ 2: короткая блокировка ТОЛЬКО на работу с Таблицей —
    // проверка-и-создание листа и запись строки атомарны.
    // ------------------------------------------------------------------
    var lock = LockService.getScriptLock();
    if (!lock.tryLock(30000)) {
      return jsonError('BUSY', 'Сервер занят обработкой других данных. Повторите попытку через минуту.');
    }

    var lastRow;
    try {
      var ss = SpreadsheetApp.getActiveSpreadsheet();

      // Лист = водитель. Создаем с шапкой при первом отчете.
      var sheet = ss.getSheetByName(safeName);
      if (!sheet) {
        sheet = ss.insertSheet(safeName);
        // v3.4: setValues вместо appendRow — единый способ записи строк во
        // всем файле (без автоопределения типов и «первой пустой строки»)
        sheet.getRange(1, 1, 1, SHEET_HEADERS.length).setValues([SHEET_HEADERS]);
        // Оформление шапки: жирный текст, голубой фон, закрепленная строка —
        // чтобы шапка всегда была видна при прокрутке длинного списка
        sheet.getRange('A1:H1').setFontWeight('bold').setBackground('#e8f0fe');
        sheet.setFrozenRows(1);
        // Колонка «Показания счетчика» (C) — ТЕКСТ: чтобы значения, введенные
        // в таблицу руками, тоже не теряли ведущие нули
        sheet.getRange('C2:C').setNumberFormat('@');
      }

      // ----------------------------------------------------------------
      // ШАГ 3: ЗАЩИТА ОТ ДУБЛЕЙ (см. блок «СКРЫТАЯ ЗАЩИТА ОТ ДУБЛЕЙ» выше).
      // Проверяем ДО записи. Дубль = отчет уже записан при прошлой попытке:
      // отвечаем «success» без записи — телефон удалит его из очереди.
      // ----------------------------------------------------------------
      if (dedupHas(safeName, data.reportId)) {
        Logger.log('Дубль отклонен: ' + data.reportId + ' (лист ' + safeName + ')');
        return jsonOut({ status: 'success', duplicate: true, sheetName: safeName });
      }

      // ----------------------------------------------------------------
      // ШАГ 4: ВРЕМЯ ЗАПОЛНЕНИЯ (одна колонка, упрощено в v3.3).
      // Телефон присылает createdAt — время заполнения по часам телефона
      // (работает одинаково офлайн и онлайн). Форматируем НА СЕРВЕРЕ:
      // в колонке всегда единый сортируемый вид. Если поле не пришло или
      // битое — берем текущее серверное время (строка не пострадает).
      // ----------------------------------------------------------------
      var createdMs = Number(data.createdAt);
      var displayTime = (data.createdAt && !isNaN(createdMs))
        ? Utilities.formatDate(new Date(createdMs), SERVER_TZ, 'dd.MM.yyyy HH:mm:ss')
        : Utilities.formatDate(new Date(), SERVER_TZ, 'dd.MM.yyyy HH:mm:ss');

      // ----------------------------------------------------------------
      // ШАГ 5: текст ячейки «Фото»: подписи ссылок + пояснения об ошибках
      // ----------------------------------------------------------------
      var photoCell = 'Без фото';
      if (photoParts.length) {
        var texts = [];
        for (var k = 0; k < photoParts.length; k++) texts.push(photoParts[k].text);
        photoCell = texts.join('\n');
      }

      // ----------------------------------------------------------------
      // ШАГ 6: ВЕДУЩИЕ НУЛИ СЧЕТЧИКА — текстовый формат ставится ДО записи
      // КАЖДОЙ строки. Почему это важно: если у ячейки формат «Автоматически»
      // (листы, созданные старыми версиями сервера), Google Таблицы
      // превращают строку '0057' в число 57 — нули пропадают. Теперь формат
      // '@' гарантирован для каждой новой строки на любом листе.
      // ----------------------------------------------------------------
      var nextRow = sheet.getLastRow() + 1;
      sheet.getRange(nextRow, 3).setNumberFormat('@'); // 3 = «Показания счетчика»

      // ШАГ 7 (ИСПРАВЛЕНО в v3.4): строка пишется через setValues, а НЕ
      // appendRow. Два дефекта старого способа:
      //   1) appendRow ищет «первую строку без данных» и после setNumberFormat
      //      на пустой ячейке мог уйти строкой ниже — между отчетами
      //      оставались пустые «дыры»;
      //   2) appendRow игнорирует формат '@' и сам распознает типы входных
      //      значений: строка '0057' вставлялась числом 57 — нули пропадали.
      // setValues пишет РОВНО в рассчитанную строку и УВАЖАЕТ формат '@'.
      // Игрушки/заманухи — ЧИСЛАМИ (фильтры и сводные работают); счетчик —
      // СТРОКОЙ (ведущие нули значимы).
      sheet.getRange(nextRow, 1, 1, 8).setValues([[
        displayTime,                  // A — время заполнения
        data.pointName,               // B — торговая точка
        data.meter || '',             // C — счетчик СТРОКОЙ: '0057' не станет 57
        Number(data.smallToys) || 0,  // D — число
        Number(data.zamanukha) || 0,  // E — число
        data.probros || '',           // F
        data.problems || 'Нет',       // G
        photoCell                     // H — ссылки/пояснения
      ]]);
      lastRow = nextRow; // строка известна точно — повторный getLastRow() не нужен

      // ----------------------------------------------------------------
      // ШАГ 8: кликабельные ссылки через RichText (не формулы HYPERLINK —
      // они зависят от локали таблицы). В одной ячейке может быть НЕСКОЛЬКО
      // ссылок — по одной на каждое загруженное фото.
      // ----------------------------------------------------------------
      if (photoParts.length) {
        var builder = SpreadsheetApp.newRichTextValue().setText(photoCell);
        var pos = 0;
        for (var j = 0; j < photoParts.length; j++) {
          if (photoParts[j].url) {
            builder.setLinkUrl(pos, pos + photoParts[j].text.length, photoParts[j].url);
          }
          pos += photoParts[j].text.length + 1; // +1 = перенос строки между частями
        }
        sheet.getRange(lastRow, 8).setRichTextValue(builder.build()); // 8 = «Фото»
      }

      // Форсируем запись до ответа клиенту
      SpreadsheetApp.flush();

      // ЗАПОМНИТЬ id ТОЛЬКО ПОСЛЕ фактической записи строки: если запись
      // упала с ошибкой, память осталась чистой и повтор пройдет без помех.
      // ИСПРАВЛЕНО (v3.4) — КРАШ-ЦИКЛ ДУБЛЕЙ: раньше исключение здесь (квота
      // PropertiesService) улетало в общий catch, телефон получал 'error',
      // отчет оставался в очереди и отправлялся снова: строка-дубль + снова
      // сбой памяти = лавина дублей. Теперь сбой памяти НЕ мешает ответу
      // 'success': строка записана, телефон удалит отчет, а потеря памяти
      // означает лишь теоретический риск РЕДКОГО одиночного дубля при потере
      // ответа в сети (сценарий ERR_TIMED_OUT).
      try {
        dedupRemember(safeName, data.reportId);
      } catch (memErr) {
        Logger.log('НЕ КРИТИЧНО: reportId не запомнен (' + (memErr.message || memErr) + '). Отчет записан, будет ответ success.');
      }

    } finally {
      // Замок освобождается ВСЕГДА, даже при ошибке записи
      try { lock.releaseLock(); } catch (e2) {}
    }

    // Только после этого ответа телефон удалит отчет из своей базы.
    return jsonOut({ status: 'success', row: lastRow, sheetName: safeName });

  } catch (err) {
    // Любая НЕОЖИДАННАЯ ошибка — SERVER (временная): телефон повторит позже.
    // Сознательно НЕ «постоянная»: блокировка/квоты Google — лечатся,
    // и отчеты должны дождаться исправления, а не отложиться навсегда.
    Logger.log('ОШИБКА doPost: ' + (err.message || err));
    return jsonError('SERVER', err.message || String(err));
  }
}
