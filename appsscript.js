/**
 * ============================================================================
 * БЭКЕНД PWA «ОТЧЕТ ЭКСПЕДИТОРА» — версия 3.2
 * ============================================================================
 * РОЛЬ: серверная часть на Google Apps Script. Принимает отчет (текст + все
 * фото одним пакетом), кладет фото в папку Google Диска, дописывает строку
 * в лист водителя (лист = ФИО, вкладки аналогично Excel).
 *
 * ЧТО НОВОГО В ВЕРСИИ 3.2:
 *   1. ИДЕМПОТЕНТНОСТЬ (защита от дублей строк): колонка 'ID отчета' +
 *      проверка ДО записи. Если ответ сервера потерялся и телефон отправил
 *      отчет повторно — дубль НЕ создается, телефон получает success и
 *      спокойно удаляет отчет из очереди.
 *   2. НЕСКОЛЬКО ФОТО: принимаем массив photos (и старый одиночный
 *      photoBase64 для совместимости). Все ссылки кликабельны в ОДНОЙ
 *      ячейке «Фото» через RichText — по одной на каждое фото.
 *   3. ЧЕСТНОЕ ВРЕМЯ: клиент присылает createdAt (миллисекунды, уже
 *      выверенные по серверу через offset) — сервер сам форматирует их в
 *      строку одного формата (сортируемо, независимо от локали телефона).
 *      Отдельная колонка «Принято сервером» НЕ нужна (решение владельца).
 *   4. КОДЫ ОШИБОК для клиента:
 *        VALIDATION — отчет не будет принят НИКОГДА (плохие данные):
 *                     телефон откладывает его в сторону, очередь идет дальше;
 *        BUSY       — временная занятость: телефон повторит позже;
 *        SERVER     — прочие сбои: телефон повторит позже.
 *   5. САМОМИГРАЦИЯ старых листов: колонка 'ID отчета' добавляется в шапку
 *      автоматически при первом же отчете — руками в таблицу лезть не надо.
 * ============================================================================
 */

// ID папки на Google Диске, куда складываются фото отчетов.
const FOLDER_ID = '1dMiGYPAnbku98DLOVZl6X8a4xR0iD-y3';

// Часовой пояс серверных меток времени.
const SERVER_TZ = 'GMT+3';

// НОМЕР колонки 'ID отчета' (A=1, B=2, ... I=9).
// Если когда-нибудь добавите колонки — не забудьте обновить эту константу.
const ID_COL = 9;

// Шапка таблицы. Порядок = порядок колонок = порядок значений в appendRow.
const SHEET_HEADERS = [
  'Дата и время создания',   // A — из createdAt клиента (выверено по серверу)
  'Торговая точка',          // B
  'Показания счетчика',      // C — ТЕКСТ: ведущие нули значимы ('0057' не равно '57')
  'Мелкие игрушки',          // D — число
  'Заманухи',                // E — число
  'Проброс',                 // F — текст (количество или комментарий)
  'Проблемы на маршруте',    // G
  'Фото',                    // H — кликабельные ссылки / пояснения
  'ID отчета'                // I — НОВОЕ: защита от дублей
];

/** Единая точка формирования JSON-ответа клиенту. */
function jsonOut(obj) {
  return ContentService
    .createTextOutput(JSON.stringify(obj))
    .setMimeType(ContentService.MimeType.JSON);
}

// ----------------------------------------------------------------------------
// НОВОЕ (v3.2): единая точка ОШИБОК. КОД обязателен — по нему телефон
// решает судьбу отчета: отложить навсегда (VALIDATION) или повторить позже.
// ----------------------------------------------------------------------------
function jsonError(code, message) {
  Logger.log('ОТКАЗ [' + code + ']: ' + message);
  return jsonOut({ status: 'error', code: code, message: message });
}

