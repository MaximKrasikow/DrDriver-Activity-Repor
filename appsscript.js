// ЗАГРУЗКА ФОТО НА GOOGLE ДИСК (v3.2: массив фото, каждое — независимо)
// ============================================================================
/**
 * ЧТО делает: декодирует каждый Base64-элемент в JPEG и кладет в папку
 * FOLDER_ID. Сбой ОДНОГО фото не мешает остальным и не отменяет отчет:
 * в ячейке «Фото» будет и ссылка на успешные, и пояснение по сбойным.
 *
 * @param {Array|null} photoList    - массив чистых Base64-строк (новый формат)
 * @param {string|null} legacySingle - одиночный Base64 (старый формат, v3.1)
 * @param {string} safeName          - имя водителя (уже очищенное)
 * @return {Array<{text: string, url: string}>} части для ячейки «Фото»:
 *         с url = кликабельная ссылка, без url = текст пояснения об ошибке
 */
function uploadPhotos(photoList, legacySingle, safeName) {
  // Совместимость: новый клиент шлет массив, старый — одиночное фото
  var photos = (photoList && photoList.length) ? photoList
             : (legacySingle ? [legacySingle] : []);
  if (!photos.length) return [];

  var parts = [];
  // Одна метка времени на ВСЕ фото отчета + номер фото: имена не пересекутся
  // даже при загрузке нескольких файлов в одну секунду.
  var dateStr = Utilities.formatDate(new Date(), SERVER_TZ, 'yyyy-MM-dd_HH-mm-ss');

  for (var i = 0; i < photos.length; i++) {
    var n = i + 1;
    try {
      var fileName = safeName + '_' + dateStr + '_' + n + '.jpg';
      var blob = Utilities.newBlob(
        Utilities.base64Decode(photos[i]), 'image/jpeg', fileName);

      var f = Drive.Files.create({
        name: fileName,
        mimeType: 'image/jpeg',
        parents: [FOLDER_ID]
      }, blob, { fields: 'id, webViewLink' });

      // «Просмотр по ссылке для всех». Права могли унаследоваться от папки —
      // повторная установка не нужна и НЕ считается ошибкой.
      try {
        Drive.Permissions.create({ role: 'reader', type: 'anyone' }, f.id);
      } catch (pErr) {
        Logger.log('Предупреждение прав доступа (не критично): ' + pErr.message);
      }

      parts.push({ text: '📷 Фото ' + n, url: f.webViewLink });

    } catch (driveErr) {
      // Сбой одного фото: отчет спасаем, в ячейке будет пояснение
      Logger.log('ОШИБКА ЗАГРУЗКИ ФОТО #' + n + ': ' + driveErr.message);
      parts.push({ text: 'Фото ' + n + ': ошибка (' + driveErr.message + ')' });
    }
  }
  return parts;
}

// ============================================================================
// ГЛАВНЫЙ ПРИЕМНИК ОТЧЕТОВ (POST-запросы от телефона водителя)
// ============================================================================
function doPost(e) {
  try {
    // --- Валидация запроса до всего остального. КОДЫ здесь = VALIDATION:
    // мусорный запрос не будет корректным НИКОГДА, телефон его отложит ---
    if (!e || !e.postData || !e.postData.contents) {
      return jsonError('VALIDATION', 'Получен пустой запрос.');
    }

    var data;
    try {
      data = JSON.parse(e.postData.contents);
    } catch (parseErr) {
      return jsonError('VALIDATION', 'Тело запроса не является корректным JSON.');
    }

    if (data.action !== 'REPORT') {
      return jsonError('VALIDATION', 'Недопустимое действие: ' + data.action);
    }
    if (!data.user || !data.pointName) {
      return jsonError('VALIDATION', 'Отсутствуют обязательные поля: водитель или торговая точка.');
    }

    // Санитизация ФИО для имени листа: запрещенные символы -> '_', до 50 симв.
    var safeName = String(data.user)
      .replace(/[\\/*?:\[\]']/g, '_')
      .trim()
      .substring(0, 50) || 'Без имени';

    // ------------------------------------------------------------------
    // ПРЕДПРОБНАЯ ПРОВЕРКА ЗАГРУЗКИ СЕРВЕРА (fail-fast оптимизация).
    // Это НЕ гарантия и не механизм защиты: между probe и записью лок может
    // занять другой водитель — тогда честно постоим в tryLock(30000) ниже.
    // Цена этой гонки — секунды ожидания, а НЕ данные (безопасно).
    // Смысл: не тратить 3-5 секунд на загрузку фото, если сервер явно занят.
    // ------------------------------------------------------------------
    var probeLock = LockService.getScriptLock();
    if (!probeLock.tryLock(1000)) {
      return jsonError('BUSY', 'Сервер перегружен другими водителями. Отчет остался в телефоне и отправится повторно автоматически.');
    }
    try { probeLock.releaseLock(); } catch (relErr) {}

    // ------------------------------------------------------------------
    // ШАГ 1: фото на Диск — БЕЗ блокировки (как в v3.1).
    // Нюанс идемпотентности: при ПОВТОРНОЙ отправке (ответ v3.1 потерялся)
    // фото загрузится заново и на Диске появится копия-«сирота». Случай
    // редкий и безвредный: в таблице дубля НЕ будет (проверка ниже),
    // лишний файл можно удалить руками. Таблица — главный источник правды.
    // ------------------------------------------------------------------
    var photoParts = uploadPhotos(data.photos, data.photoBase64, safeName);

    // ------------------------------------------------------------------
    // ШАГ 2: короткая блокировка ТОЛЬКО на работу с Таблицей —
    // проверка-и-создание листа и запись строки атомарны.
    // ------------------------------------------------------------------
    var lock = LockService.getScriptLock();
    if (!lock.tryLock(30000)) {
      return jsonError('BUSY', 'Сервер занят обработкой других данных. Повторите попытку через минуту.');
    }

    var lastRow;
    try {
      var ss = SpreadsheetApp.getActiveSpreadsheet();

      // Лист = водитель. Создаем с шапкой при первом отчете.
      var sheet = ss.getSheetByName(safeName);
      if (!sheet) {
        sheet = ss.insertSheet(safeName);
        sheet.appendRow(SHEET_HEADERS);
        sheet.getRange('A1:I1').setFontWeight('bold').setBackground('#e8f0fe');
        sheet.setFrozenRows(1);
        // НОВОЕ: колонки C (счетчик) и I (ID) — как ТЕКСТ: '0057' не
        // превратится в 57, id отчета не искажается
        sheet.getRange('C1:C').setNumberFormat('@');
        sheet.getRange('I1:I').setNumberFormat('@');
      } else if (sheet.getRange(1, ID_COL).getValue() !== 'ID отчета') {
        // НОВОЕ: САМОМИГРАЦИЯ листа, созданного версией 3.1 без колонки ID.
        // Выполняется ОДИН раз, дальше эта ветка не срабатывает.
        sheet.getRange(1, ID_COL).setValue('ID отчета')
             .setFontWeight('bold').setBackground('#e8f0fe');
        sheet.getRange('C2:C').setNumberFormat('@');
      }

      // ----------------------------------------------------------------
      // ШАГ 3: ЗАЩИТА ОТ ДУБЛЕЙ (идемпотентность) — ГЛАВНОЕ НОВШЕСТВО.
      // Сценарий без этой проверки: сервер записал строку -> ответ потерялся
      // (обрыв связи / таймаут телефона) -> телефон отправил отчет повторно
      // -> ВТОРАЯ такая же строка. Теперь: если reportId уже в таблице —
      // строку НЕ пишем, отвечаем success (телефон удалит отчет из очереди).
      // ----------------------------------------------------------------
      lastRow = sheet.getLastRow();
      if (data.reportId && lastRow > 1) {
        var ids = sheet.getRange(2, ID_COL, lastRow - 1, 1).getValues();
        for (var i = 0; i < ids.length; i++) {
          // Сравниваем ТОЛЬКО непустые ячейки: у листа, мигрированного с v3.1,
          // старые строки имеют пустой ID — они никогда не должны совпасть
          // ни с каким reportId (в т.ч. экзотическим вроде строки 'null')
          if (ids[i][0] && String(ids[i][0]) === String(data.reportId)) {
            Logger.log('Дубль отклонен: ' + data.reportId +
                       ' (лист ' + safeName + ', строка ' + (i + 2) + ')');
            return jsonOut({ status: 'success', duplicate: true, sheetName: safeName });
          }
        }
      }

      // ----------------------------------------------------------------
      // ШАГ 4: ЧЕСТНОЕ ВРЕМЯ (одна колонка, как решено с владельцем).
      // Клиент шлет createdAt (мс, выверенные по серверу через offset).
      // Форматируем НА СЕРВЕРЕ: формат в таблице всегда одинаковый и
      // сортируемый, независимо от настроек телефона водителя.
      // ----------------------------------------------------------------
      var displayTime;
      var createdMs = Number(data.createdAt);
      if (data.createdAt && !isNaN(createdMs)) {
        displayTime = Utilities.formatDate(new Date(createdMs), SERVER_TZ, 'dd.MM.yyyy HH:mm:ss');
      } else if (data.timestamp) {
        displayTime = String(data.timestamp); // страховка для очень старых клиентов
      } else {
        displayTime = Utilities.formatDate(new Date(), SERVER_TZ, 'dd.MM.yyyy HH:mm:ss');
      }

      // ----------------------------------------------------------------
      // ШАГ 5: текст ячейки «Фото»: подписи ссылок + пояснения об ошибках
      // ----------------------------------------------------------------
      var photoCell = 'Без фото';
      if (photoParts.length) {
        var texts = [];
        for (var k = 0; k < photoParts.length; k++) texts.push(photoParts[k].text);
        photoCell = texts.join('\n');
      }

      // ----------------------------------------------------------------
      // ШАГ 6: строка отчета. Игрушки/заманухи — ЧИСЛАМИ (фильтры и сводные
      // работают); счетчик — строкой (ведущие нули значимы).
      // ----------------------------------------------------------------
      sheet.appendRow([
        displayTime,
        data.pointName,
        data.meter || '',
        Number(data.smallToys) || 0,
        Number(data.zamanukha) || 0,
        data.probros || '',
        data.problems || 'Нет',
        photoCell,
        data.reportId || ''
      ]);
      lastRow = sheet.getLastRow();

      // НОВОЕ (доработка): честное время — видимость для руководителя.
      // timeSource='device' означает «часы телефона не сверялись с сервером»
      // (телефон ни разу не был онлайн до отправки). Ставим ПРИМЕЧАНИЕ (note)
      // к ячейке даты, а НЕ отдельную колонку (решение владельца): при
      // наведении курсора пометка видна, сортировка и фильтры не страдают.
      if (data.timeSource === 'device') {
        sheet.getRange(lastRow, 1).setNote('Время по часам телефона, без сверки с сервером.');
      }

      // ----------------------------------------------------------------
      // ШАГ 7: кликабельные ссылки через RichText (не формулы HYPERLINK —
      // они зависели от локали таблицы). НОВОЕ: в одной ячейке может быть
      // НЕСКОЛЬКО ссылок — по одной на каждое загруженное фото.
      // ----------------------------------------------------------------
      if (photoParts.length) {
        var builder = SpreadsheetApp.newRichTextValue().setText(photoCell);
        var pos = 0;
        for (var j = 0; j < photoParts.length; j++) {
          if (photoParts[j].url) {
            builder.setLinkUrl(pos, pos + photoParts[j].text.length, photoParts[j].url);
          }
          pos += photoParts[j].text.length + 1; // +1 = перенос строки между частями
        }
        sheet.getRange(lastRow, 8).setRichTextValue(builder.build());
      }

      // Форсируем запись до ответа клиенту
      SpreadsheetApp.flush();

    } finally {
      // Замок освобождается ВСЕГДА, даже при ошибке записи
      try { lock.releaseLock(); } catch (e2) {}
    }

    // Только после этого ответа телефон удалит отчет из своей базы.
    return jsonOut({ status: 'success', row: lastRow, sheetName: safeName });

  } catch (err) {
    // Любая НЕОЖИДАННАЯ ошибка — SERVER (временная): телефон повторит позже.
    // Сознательно НЕ «постоянная»: блокировка/квоты Google — лечатся,
    // и отчеты должны дождаться исправления, а не отложиться навсегда.
    Logger.log('ОШИБКА doPost: ' + (err.message || err));
    return jsonError('SERVER', err.message || String(err));
  }
}
